"""Generate promptfooconfig.yaml from the same corpus the runner uses.

Written rather than hand-maintained so the two paths cannot drift: if a case is
added to corpus.jsonl, it appears here on the next build.

    python -m promptfoo_int.build_config --layer L5 --limit 24
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).parent.parent


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--layer", default="L5")
    ap.add_argument("--model", default="qwen3.5:4b")
    ap.add_argument("--limit", type=int, default=24, help="0 for the full corpus")
    args = ap.parse_args()

    import sys

    sys.path.insert(0, str(ROOT))
    from runner.run import stratified

    rows = [
        json.loads(l)
        for l in (ROOT / "attacks" / "corpus.jsonl").read_text().splitlines()
        if l.strip()
    ]
    cases = stratified(rows, args.limit) if args.limit else rows

    lines = [
        "# GENERATED by `python -m promptfoo_int.build_config` -- do not edit.",
        "#",
        "# Runs the same corpus, the same agent, and the same graders as",
        "# `python -m runner.run`. tests/test_promptfoo_parity.py asserts both",
        "# paths report the same attack success rate.",
        "",
        f"description: Gauntlet prompt-injection suite ({args.layer}, {args.model})",
        "",
        "prompts:",
        "  - '{{case_id}}'",
        "",
        "providers:",
        "  - id: 'file://promptfoo_int/provider.py'",
        f"    label: gauntlet-{args.layer}",
        "    config:",
        f"      layer: {args.layer}",
        f"      model: {args.model}",
        "",
        "defaultTest:",
        "  assert:",
        "    - type: python",
        "      value: file://promptfoo_int/assert_not_violated.py",
        "",
        "tests:",
    ]
    for case in cases:
        lines.append(f"  - description: '{case['id']} {case['category']}/{case['technique']}'")
        lines.append("    vars:")
        lines.append(f"      case_id: {case['id']}")

    out = ROOT / "promptfooconfig.yaml"
    out.write_text("\n".join(lines) + "\n")
    print(f"{out.name}: {len(cases)} cases, layer {args.layer}, model {args.model}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
